/* ============================================================================
   TASKS

   `due` is the sortable date. `dueLabel` is what the column shows, because
   "Today" and "Overdue 2 d" say more at a glance than a date the reader has
   to compare against today's.

   FOUR FIELDS THE COLUMNS NEVER SHOW — `type`, `description`, `created` and
   `history` — exist for the detail panel that opens beside the worklist. They
   are here rather than derived at render time because none of them can be:
   `detail` is the one line that fits in a cell, and the paragraph a person
   needs before deciding what to do is a different sentence, not a longer one.

   `history` is the panel's timeline, oldest first. Each entry is who did it,
   what they did, when, and whether the actor was a person or the system —
   `kind` picks the mark beside the entry, because "the software noticed this"
   and "a colleague asked you for this" are read differently and a column of
   identical dots hides that difference. Acting on a task from the panel
   appends to this array, so the trail stays true within a session.

   `comments` is the conversation about the task, and it is a SEPARATE array
   from `history` on purpose. The timeline is a record of what was done to the
   task — filed, assigned, started, moved — and every entry in it is a fixed
   phrase the panel can rely on. A comment is somebody talking: it answers a
   question, it disagrees, it asks for the chart to be pulled, and none of that
   is a state change. Folded into one list the two would fight — a trail read
   for "where has this got to" would be three-quarters discussion, and a thread
   read for "what did Kirstin say" would be three-quarters system lines. Two
   lists behind two tabs lets each be read for what it is.

   Each comment is who wrote it, when, and the words. Oldest first here, the
   same as `history`; the panel turns them round, for the reason given there.
   ========================================================================= */

