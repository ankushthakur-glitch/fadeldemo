/**
 * Build the sprite markup once.
 *
 * The paint attributes go on every <symbol>, not just the sprite root. When
 * <use> clones a symbol it re-parents the copy, so anything the symbol was
 * merely *inheriting* from the sprite root is lost and the glyph renders with
 * the browser's default black fill. Setting them per-symbol makes each icon
 * self-contained. `fill="currentColor"` still resolves against wherever the
 * icon is used, so an icon keeps matching its surrounding text.
 */
function spriteMarkup() {
  const paint = 'fill="currentColor" stroke="none"';

  const symbols = Object.entries(ICONS)
    .map(
      ([name, body]) =>
        `<symbol id="i-${name}" viewBox="0 0 256 256" ${paint}>${body}</symbol>`
    )
    .join('');

  return `<svg xmlns="http://www.w3.org/2000/svg" id="${SPRITE_ID}" aria-hidden="true" focusable="false" class="ui-icon-sprite">${symbols}</svg>`;
}

/** Inject the sprite into <body> if it is not already there. */
export function installIconSprite() {
  if (document.getElementById(SPRITE_ID)) return;
  document.body.insertAdjacentHTML('afterbegin', spriteMarkup());
}

/** Markup for a single icon — used by components that build their own DOM. */
export function iconMarkup(name, className = 'ui-icon') {
  return `<svg class="${className}" aria-hidden="true" focusable="false"><use href="#i-${name}"></use></svg>`;
}

