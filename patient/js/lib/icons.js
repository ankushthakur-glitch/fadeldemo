/** Injects the sprite once. Safe to call from every page and every module. */
export function installIconSprite() {
  const ID = 'pp-icon-sprite';
  if (document.getElementById(ID)) return;

  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.id = ID;
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  // Out of flow AND out of the accessibility tree. display:none would work
  // too, but Safari has historically refused to resolve <use> into a hidden
  // sprite, and a portal that loses every icon on one browser is not a
  // trade worth making for one line of CSS.
  svg.style.cssText = 'position:absolute;width:0;height:0;overflow:hidden';

  // fill/stroke are set per-symbol, not on this root: <use> re-parents the
  // clone, so anything merely inherited from here is lost and the glyph comes
  // out in the browser's default black.
  svg.innerHTML = Object.entries(SYMBOLS)
    .map(
      ([name, body]) =>
        `<symbol id="pi-${name}" viewBox="0 0 256 256" fill="currentColor" stroke="none">${body}</symbol>`
    )
    .join('');

  const attach = () => document.body.prepend(svg);
  if (document.body) attach();
  else document.addEventListener('DOMContentLoaded', attach, { once: true });
}

/** Markup for one icon. Handy when a screen builds rows as HTML strings. */
export function icon(name, { size = '', className = '' } = {}) {
  const classes = ['pp-icon', size && `pp-icon--${size}`, className].filter(Boolean).join(' ');
  return `<svg class="${classes}" aria-hidden="true"><use href="#pi-${name}"></use></svg>`;
}
